const createPromptFromFileName = (fileName: string) => {
  const normalized = fileName.toLowerCase();

  if (normalized.includes('halloween')) {
    return 'Create an image of a polished Halloween creator-gallery scene with playful spooky details, cinematic lighting, rich color contrast, and a clean social-media-ready composition.';
  }

  if (normalized.includes('christmas')) {
    return 'Create an image of a warm Christmas visual with festive objects, soft glowing lights, refined winter colors, and a polished creator-gallery composition.';
  }

  if (normalized.includes('thanksgiving')) {
    return 'Create an image of a Thanksgiving-inspired scene with warm harvest colors, cozy table styling, soft natural light, and an inviting seasonal mood.';
  }

  if (normalized.includes('happy new year') || normalized.includes('new year')) {
    return 'Create an image of a Happy New Year celebration with luminous festive details, elegant composition, rich contrast, and an optimistic cinematic atmosphere.';
  }

  if (normalized.includes('imagine')) {
    return 'Create an image of an imaginative AI scene for an inspiration gallery, with a clear visual subject, expressive mood, polished lighting, and strong composition.';
  }

  if (normalized.includes('creator gallery')) {
    return 'Create an image of a creator-gallery artwork with a memorable subject, refined AI visual style, strong focal point, and polished editorial lighting.';
  }

  return 'Create an image of an experimental AI-generated artwork with a clear subject, strong composition, expressive lighting, and a polished gallery-ready finish.';
};

const createLabelFromFileName = (fileName: string) =>
  fileName
    .replace(/\.(png|jpe?g|webp)$/i, '')
    .replace(/__/g, ' / ')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

